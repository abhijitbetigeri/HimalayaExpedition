"""Objective D: fixed-line ascent -- climbing an icy slope on a rope.

The MuJoCo track built `fixed_line.py` and reasoned the design out properly:
real climbers do NOT grip the rope, they clip a mechanical ascender that slides up
freely and locks under load, so modelling grip as a MECHANISM is the faithful
choice rather than a shortcut. A rigid constraint was rejected there after it
carried 327 N of a 330 N robot -- a zip line, not an ascent.

Nothing trains in MuJoCo, so this ports the same idea to Isaac using the mechanism
that is already proven here: an external force on the torso. A tether is an upward
assist force, roughly a third of body weight, which is what taking your own weight
on an ascender feels like -- it helps, it does not carry you.

Built on the ice+slope config that reached 93.5%, so this is one change from a
known-good recipe -- the discipline that has separated every run that worked here
from every run that did not.

The tether is NOT in the policy observation. The robot must feel the assist
through its own dynamics, exactly as it must feel the surface -- same argument as
wind, and what makes the behaviour transferable.

Run:
  hf jobs uv run --detach --namespace iteratehack --flavor l40sx1 --timeout 3h \
      --env OMNI_KIT_ACCEPT_EULA=YES \
      -v hf://buckets/iteratehack/jobs-artifacts:/mnt \
      --label name=himalaya-traction --label task=train-tether \
      train_tether.py
"""

