G1DIR = pathlib.Path(f"{LAB}/source/isaaclab_tasks/isaaclab_tasks/manager_based/"
                     f"locomotion/velocity/config/g1")
(G1DIR / "tether_env_cfg.py").write_text(textwrap.dedent('''
    """G1 ascending an icy slope on a fixed line. Generated by train_tether.py."""
    import isaaclab.envs.mdp as mdp
    from isaaclab.managers import EventTermCfg as EventTerm
    from isaaclab.managers import SceneEntityCfg
    from isaaclab.utils.configclass import configclass

    from .rough_env_cfg import G1RoughEnvCfg


    @configclass
    class G1TetherEnvCfg(G1RoughEnvCfg):
        def __post_init__(self):
            super().__post_init__()

            # ice -> rock, as in the 93.5% ice+slope run
            self.events.physics_material.params["static_friction_range"] = (0.05, 1.0)
            self.events.physics_material.params["dynamic_friction_range"] = (0.04, 0.9)
            self.rewards.feet_slide.weight = -0.01

            # The ascender: a sustained upward assist at the torso, re-applied
            # every 0.4-1.0 s so it is a continuous load rather than a shove.
            #
            # The G1 is ~35 kg (~340 N). 80-140 N up is roughly a third of body
            # weight -- what taking your weight on a jumar feels like. It helps you
            # up the slope; it does not carry you, which is the failure mode that
            # made the MuJoCo rigid-constraint version a zip line.
            self.events.tether = EventTerm(
                func=mdp.apply_external_force_torque,
                mode="interval",
                interval_range_s=(0.4, 1.0),
                params={
                    "asset_cfg": SceneEntityCfg("robot", body_names=["torso_link"]),
                    "force_range": (80.0, 140.0),
                    "torque_range": (-5.0, 5.0),
                },
            )
            # Climbing means going UP the slope steadily, not strolling.
            self.commands.base_velocity.ranges.lin_vel_x = (0.4, 0.9)


    @configclass
    class G1TetherEnvCfg_PLAY(G1TetherEnvCfg):
        def __post_init__(self):
            super().__post_init__()
            self.scene.num_envs = 1
            self.observations.policy.enable_corruption = False
'''))

