EVAL = textwrap.dedent('''
    import json, os, pathlib
    os.environ["OMNI_KIT_ACCEPT_EULA"] = "YES"
    os.environ.setdefault("HOME", "/root")
    from isaaclab.app import AppLauncher
    app = AppLauncher(headless=True, device="cuda:0").app

    import gymnasium as gym, torch
    import isaaclab_tasks  # noqa
    from isaaclab_tasks.utils import parse_env_cfg
    from isaaclab_rl.rsl_rl import RslRlVecEnvWrapper
    from rsl_rl.runners import OnPolicyRunner
    from isaaclab_tasks.utils import load_cfg_from_registry

    BUCKET = pathlib.Path("/mnt/himalaya-g1")
    POLICIES = {
        "baseline": BUCKET / "baseline/rsl_rl/g1_flat/2026-08-29_20-54-12/model_1499.pt",
        "ice":      BUCKET / "ice-isaac/rsl_rl/g1_flat/2026-08-29_21-48-51/model_1499.pt",
    }
    SURFACES = {"rock": "Isaac-Eval-G1-Rock-v0", "ice": "Isaac-Eval-G1-Ice-v0"}
    N_ENVS, STEPS = 256, 400

    results = {}
    for sname, task in SURFACES.items():
        cfg = parse_env_cfg(task, device="cuda:0", num_envs=N_ENVS)
        env = gym.make(task, cfg=cfg)
        env = RslRlVecEnvWrapper(env)
        agent_cfg = load_cfg_from_registry(task, "rsl_rl_cfg_entry_point")

        for pname, ckpt in POLICIES.items():
            if not ckpt.exists():
                print("MISSING", ckpt, flush=True); continue
            runner = OnPolicyRunner(env, agent_cfg.to_dict(), log_dir=None,
                                    device="cuda:0")
            runner.load(str(ckpt))
            policy = runner.get_inference_policy(device="cuda:0")

            obs, _ = env.get_observations()
            fell = torch.zeros(N_ENVS, dtype=torch.bool, device="cuda:0")
            alive_steps = torch.zeros(N_ENVS, device="cuda:0")
            with torch.inference_mode():
                for _ in range(STEPS):
                    actions = policy(obs)
                    obs, _, dones, _ = env.step(actions)
                    newly = dones.bool() & ~fell
                    alive_steps[newly] = alive_steps[newly]
                    fell |= dones.bool()
                    alive_steps[~fell] += 1

            fall_rate = fell.float().mean().item()
            results[f"{pname}|{sname}"] = {
                "fall_rate": round(fall_rate, 4),
                "survival_rate": round(1.0 - fall_rate, 4),
                "mean_alive_steps": round(alive_steps.mean().item(), 1),
                "of_steps": STEPS,
            }
            print(f"{pname:9s} on {sname:5s}: survival "
                  f"{100*(1-fall_rate):5.1f}%  mean_alive "
                  f"{alive_steps.mean().item():5.1f}/{STEPS}", flush=True)
        env.close()

    out = BUCKET / "diagnostics"
    out.mkdir(parents=True, exist_ok=True)
    (out / "isaac_cross_eval.json").write_text(json.dumps(results, indent=2))

    print("\\n" + "="*62, flush=True)
    print(f"{'':12s}{'eval on ROCK':>22s}{'eval on ICE':>22s}")
    for p in ["baseline", "ice"]:
        r = results.get(f"{p}|rock", {}); i = results.get(f"{p}|ice", {})
        print(f"{p:12s}{r.get('survival_rate', 0)*100:>21.1f}%"
              f"{i.get('survival_rate', 0)*100:>21.1f}%", flush=True)
    print("="*62, flush=True)
    app.close()
''')
pathlib.Path("cross.py").write_text(EVAL)
