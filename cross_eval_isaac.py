"""The Isaac A/B: both policies, both surfaces, identical conditions.

Why this exists
---------------
Training metrics showed baseline 98.0% survival and ice 97.8% -- but each on its
OWN distribution (baseline at mu=0.8 fixed, ice across 0.05-1.0). That comparison
is worth nothing on its own; it is the same trap CLAUDE.md flags for the MuJoCo
arm. The claim needs each policy measured on the SAME ground:

                    eval on ROCK (mu=0.8)     eval on ICE (mu=0.08)
    baseline           expect ~98%               expect collapse   <- the demo
    ice policy         must NOT regress          expect survival   <- the proof

Bottom-left is the one people forget. If the ice policy walks on ice but has
quietly gotten worse on rock, that is a trade, not a win, and a judge will ask.

Eval friction is pinned to a POINT in each condition, not a range, so the two
policies see identical ground rather than two different random draws.

Run:
  hf jobs uv run --detach --namespace iteratehack --flavor l4x1 --timeout 45m \
      --env OMNI_KIT_ACCEPT_EULA=YES \
      -v hf://buckets/iteratehack/jobs-artifacts:/mnt \
      --label name=himalaya-traction --label task=cross-eval \
      cross_eval_isaac.py
"""

