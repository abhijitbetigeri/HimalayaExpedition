(G1DIR / "mu_env_cfg.py").write_text(textwrap.dedent('''
    """Ice env for mu-estimation data collection. Generated by estimate_mu.py."""
    from isaaclab.utils.configclass import configclass
    from .flat_env_cfg import G1FlatEnvCfg


    @configclass
    class G1MuEnvCfg(G1FlatEnvCfg):
        def __post_init__(self):
            super().__post_init__()
            self.events.physics_material.params["static_friction_range"] = (0.05, 1.0)
            self.events.physics_material.params["dynamic_friction_range"] = (0.04, 0.9)
            self.rewards.feet_slide.weight = -0.01
            # Clean signal: the estimator should learn friction, not observation
            # noise, and pushes would inject forces unrelated to the surface.
            self.observations.policy.enable_corruption = False
            self.events.push_robot = None
            # Keep them walking so there is gait to read friction from. A standing
            # robot leaves almost no signal in proprioception.
            self.commands.base_velocity.ranges.lin_vel_x = (0.6, 0.6)
            self.commands.base_velocity.ranges.lin_vel_y = (0.0, 0.0)
            self.commands.base_velocity.ranges.ang_vel_z = (0.0, 0.0)
            self.commands.base_velocity.resampling_time_range = (1e6, 1e6)
'''))
