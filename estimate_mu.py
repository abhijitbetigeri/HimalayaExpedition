"""Layer 1: can the robot tell what it is standing on, from proprioception alone?

This is the piece that separates "we widened a domain-randomisation range" (a
config change) from a system that KNOWS the surface it is on and can report it.
It is also what the 340-byte Iridium telemetry packet would carry.

Why offline regression instead of teacher-student RL
----------------------------------------------------
COLA (arXiv 2510.14293) trains a privileged teacher and distils it into a
proprioception-only student -- correct, and expensive. But the estimator does not
have to be learned jointly with the policy: friction is a property of the episode,
not of the action. So roll the FIXED ice policy across randomised friction, log
(observation history -> true mu) pairs, and fit a regressor. Supervised, one pass,
minutes of GPU rather than hours.

The honest test is generalisation to friction values held out of training, which
is what the log at the end reports.

What the policy can actually see
--------------------------------
Only the 123-dim policy observation -- joint positions, joint velocities, previous
actions, IMU. NOT contact forces or foot velocities: those are privileged in Isaac
Lab and absent on real hardware. COLA's insight is that the offset between a joint's
commanded and achieved position is a proxy for the force it met, which is exactly
the signal a slipping foot leaves in proprioception. A history window is required
because friction is not observable from one frame.

Run:
  hf jobs uv run --detach --namespace iteratehack --flavor l4x1 --timeout 60m \
      --env OMNI_KIT_ACCEPT_EULA=YES \
      -v hf://buckets/iteratehack/jobs-artifacts:/mnt \
      --label name=himalaya-traction --label task=estimate-mu \
      estimate_mu.py
"""

