MU = textwrap.dedent(f'''
    import json, os, pathlib
    os.environ["OMNI_KIT_ACCEPT_EULA"] = "YES"
    os.environ.setdefault("HOME", "/root")
    from isaaclab.app import AppLauncher
    app = AppLauncher(headless=True, device="cuda:0").app

    import gymnasium as gym, torch, torch.nn as nn, numpy as np
    import isaaclab_tasks  # noqa
    from isaaclab_tasks.utils import parse_env_cfg

    DEV = "cuda:0"
    N_ENVS, WARMUP, COLLECT = 512, 60, 260
    HIST = 25                      # COLA ablated 10/25/50 and chose 25
    OUT = pathlib.Path("/mnt/himalaya-g1/mu_estimator"); OUT.mkdir(parents=True, exist_ok=True)

    policy = torch.jit.load("{POLICY}").to(DEV).eval()
    cfg = parse_env_cfg("Isaac-Mu-G1-v0", device=DEV, num_envs=N_ENVS)
    env = gym.make("Isaac-Mu-G1-v0", cfg=cfg)
    obs_d, _ = env.reset()
    obs = obs_d["policy"]
    OBS_D = obs.shape[-1]
    print(f"obs dim {{OBS_D}}, {{N_ENVS}} envs, history {{HIST}}", flush=True)

    # Ground truth: the friction PhysX actually applied this episode. Material
    # tensor is [num_envs, num_shapes, 3] = (static, dynamic, restitution).
    view = env.unwrapped.scene["robot"].root_physx_view
    mats = torch.as_tensor(np.asarray(view.get_material_properties()), device=DEV)
    mu_true = mats[:, 0, 0].clone()
    print(f"true mu: min {{mu_true.min():.3f}} max {{mu_true.max():.3f}} "
          f"mean {{mu_true.mean():.3f}}", flush=True)

    ring = torch.zeros(N_ENVS, HIST, OBS_D, device=DEV)
    X, Y = [], []
    with torch.inference_mode():
        for step in range(WARMUP + COLLECT):
            act = policy(obs)
            obs_d, _, term, trunc, _ = env.step(act)
            obs = obs_d["policy"]
            ring = torch.roll(ring, -1, dims=1); ring[:, -1] = obs
            # Skip envs that reset this step: their history straddles two episodes
            # (and two friction draws), so those windows are mislabelled.
            fresh = ~(term.bool() | trunc.bool())
            if step >= WARMUP and step % 3 == 0:
                X.append(ring[fresh].reshape(int(fresh.sum()), -1).cpu())
                Y.append(mu_true[fresh].cpu())
    env.close()

    X = torch.cat(X); Y = torch.cat(Y)
    print(f"dataset: {{tuple(X.shape)}} -> {{tuple(Y.shape)}}", flush=True)

    # Held-out by FRICTION VALUE, not at random: a random split leaks, because
    # windows from the same episode share a label and would appear on both sides.
    # Generalising to unseen mu is the claim worth making.
    lo, hi = torch.quantile(Y, torch.tensor([0.35, 0.65]))
    test_mask = (Y >= lo) & (Y <= hi)          # hold out the MIDDLE band
    Xtr, Ytr = X[~test_mask].to(DEV), Y[~test_mask].to(DEV)
    Xte, Yte = X[test_mask].to(DEV), Y[test_mask].to(DEV)
    print(f"train {{len(Xtr)}} (mu outside [{{lo:.2f}},{{hi:.2f}}]) / "
          f"test {{len(Xte)}} (inside)", flush=True)

    mean, std = Xtr.mean(0, keepdim=True), Xtr.std(0, keepdim=True) + 1e-6
    # Predict log mu: the range spans 20x and relative error is what matters.
    ytr, yte = torch.log(Ytr), torch.log(Yte)

    net = nn.Sequential(nn.Linear(X.shape[1], 512), nn.ELU(),
                        nn.Linear(512, 256), nn.ELU(),
                        nn.Linear(256, 1)).to(DEV)
    opt = torch.optim.AdamW(net.parameters(), lr=1e-3, weight_decay=1e-4)
    for ep in range(40):
        perm = torch.randperm(len(Xtr), device=DEV)
        tot = 0.0
        for i in range(0, len(perm), 4096):
            idx = perm[i:i+4096]
            loss = nn.functional.mse_loss(
                net((Xtr[idx] - mean) / std).squeeze(-1), ytr[idx])
            opt.zero_grad(); loss.backward(); opt.step()
            tot += loss.item() * len(idx)
        if ep % 10 == 9:
            with torch.no_grad():
                pt = net((Xte - mean) / std).squeeze(-1)
                r2 = 1 - ((pt - yte)**2).sum() / ((yte - yte.mean())**2).sum()
                print(f"  epoch {{ep+1:3d}}  train {{tot/len(Xtr):.4f}}  "
                      f"heldout R2 {{r2:.3f}}", flush=True)

    with torch.no_grad():
        pred = torch.exp(net((Xte - mean) / std).squeeze(-1))
        r2 = (1 - ((torch.log(pred) - yte)**2).sum()
                / ((yte - yte.mean())**2).sum()).item()
        rel = ((pred - Yte).abs() / Yte).mean().item()
        # Does it separate ice from rock at all? That is the operational question.
        is_ice = Yte < 0.15
        acc = ((pred < 0.15) == is_ice).float().mean().item() if is_ice.any() else float("nan")

    res = {{"held_out_R2_logmu": round(r2, 4),
           "mean_relative_error": round(rel, 4),
           "ice_vs_rock_accuracy": round(acc, 4),
           "history_len": HIST, "obs_dim": OBS_D,
           "n_train": len(Xtr), "n_test": len(Xte),
           "heldout_mu_band": [round(lo.item(), 3), round(hi.item(), 3)]}}
    print("\\n" + json.dumps(res, indent=2), flush=True)
    (OUT / "mu_estimator_results.json").write_text(json.dumps(res, indent=2))
    torch.save({{"state_dict": net.state_dict(), "mean": mean.cpu(), "std": std.cpu(),
                "hist": HIST, "obs_dim": OBS_D}}, OUT / "mu_estimator.pt")
    print("saved estimator ->", OUT / "mu_estimator.pt", flush=True)
    app.close()
''')
pathlib.Path("mu.py").write_text(MU)
