(G1DIR / "slopefilm_env_cfg.py").write_text(textwrap.dedent('''
    """Slope terrain at walkable winter frictions. Generated by film_slope.py."""
    from isaaclab.utils.configclass import configclass
    import isaaclab.terrains as terrain_gen
    from isaaclab.terrains import TerrainGeneratorCfg
    from .rough_env_cfg import G1RoughEnvCfg

    # A clean incline, not the stock rough mix. The default generator produces
    # blocks and stairs, which is why the first slope clips showed terrain and no
    # robot -- it was behind them.
    PURE_SLOPE = TerrainGeneratorCfg(
        size=(10.0, 10.0), border_width=15.0, num_rows=2, num_cols=2,
        horizontal_scale=0.1, vertical_scale=0.005, slope_threshold=0.75,
        use_cache=True,
        sub_terrains={"slope": terrain_gen.HfPyramidSlopedTerrainCfg(
            proportion=1.0, slope_range=(0.20, 0.30),
            platform_width=3.0, border_width=0.5)},
    )


    class _Base(G1RoughEnvCfg):
        def __post_init__(self):
            super().__post_init__()
            # Generating rough terrain is what blew the export timeout the first
            # time. Cache it so the second env build reuses the first one's mesh.
            self.scene.terrain.terrain_type = "generator"
            self.scene.terrain.terrain_generator = PURE_SLOPE
            self.rewards.feet_slide.weight = -0.01
            self.observations.policy.enable_corruption = False
            self.events.push_robot = None
            self.events.base_external_force_torque = None
            # One robot: on generated terrain the camera anchors to an env origin,
            # and with several the subject ends up a speck on a distant tile.
            self.scene.num_envs = 1
            # Steady forward march rather than resampled commands.
            self.commands.base_velocity.ranges.lin_vel_x = (0.7, 0.7)
            self.commands.base_velocity.ranges.lin_vel_y = (0.0, 0.0)
            self.commands.base_velocity.ranges.ang_vel_z = (0.0, 0.0)
            self.commands.base_velocity.resampling_time_range = (1e6, 1e6)


    @configclass
    class G1SlopeSnowCfg(_Base):
        def __post_init__(self):
            super().__post_init__()
            self.events.physics_material.params["static_friction_range"] = (0.20, 0.20)
            self.events.physics_material.params["dynamic_friction_range"] = (0.16, 0.16)


    @configclass
    class G1SlopeIceCfg(_Base):
        def __post_init__(self):
            super().__post_init__()
            self.events.physics_material.params["static_friction_range"] = (0.12, 0.12)
            self.events.physics_material.params["dynamic_friction_range"] = (0.10, 0.10)


    # Training config, needed by play.py to export the policy.
    @configclass
    class G1IceSlopeEnvCfg(G1RoughEnvCfg):
        def __post_init__(self):
            super().__post_init__()
            self.events.physics_material.params["static_friction_range"] = (0.05, 1.0)
            self.events.physics_material.params["dynamic_friction_range"] = (0.04, 0.9)
            self.rewards.feet_slide.weight = -0.01
'''))
