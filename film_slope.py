"""Export and film the ice+slope policy -- the mountain case.

Trained on Isaac Lab's ROUGH terrain (generated slopes, stairs, obstacles) with
friction spanning ice to rock, reaching 93.5% survival and 0.774 tracking. It is
the only policy here that has ever seen an incline, and it carries the height
scanner, so it can see terrain ahead rather than only feel the ground underfoot.

Two stages because the exported TorchScript does not exist yet:
  1. run play.py once against the checkpoint -- it writes exported/policy.pt NEXT
     TO THE CHECKPOINT (in the bucket), which is the detail that cost an earlier
     job when I searched IsaacLab/logs instead
  2. drive an explicit capture loop, since play.py --video records nothing

Filmed on the ROUGH terrain it was trained for, at two surfaces:
    snow  mu = 0.20   packed snow / neve -- what an approach march crosses
    ice   mu = 0.12   hard glacial ice

mu = 0.06 (bare wet ice) is deliberately NOT filmed as a headline: it is near the
physical limit for a legged system -- humans need crampons -- so a robot falling
there is physics, not a policy failure.

Run:
  hf jobs uv run --detach --namespace iteratehack --flavor l40sx1 --timeout 50m \
      --env OMNI_KIT_ACCEPT_EULA=YES \
      -v hf://buckets/iteratehack/jobs-artifacts:/mnt \
      --label name=himalaya-traction --label task=film-slope \
      film_slope.py
"""

