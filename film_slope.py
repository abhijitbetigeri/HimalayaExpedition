# ---- stage 2: film -------------------------------------------------------------
FILM = textwrap.dedent(f'''
    import json, os, pathlib
    os.environ["OMNI_KIT_ACCEPT_EULA"] = "YES"
    os.environ.setdefault("HOME", "/root")
    from isaaclab.app import AppLauncher
    app = AppLauncher(headless=True, enable_cameras=True, device="cuda:0").app

    import gymnasium as gym, torch, imageio, numpy as np
    import isaaclab_tasks  # noqa
    from isaaclab_tasks.utils import parse_env_cfg

    OUT = pathlib.Path("/mnt/himalaya-g1/videos"); OUT.mkdir(parents=True, exist_ok=True)
    STEPS = 1500
    policy = torch.jit.load("{EXPORTED}").to("cuda:0").eval()

    report = {{}}
    for tag, task in [("slope_snow", "Isaac-SlopeFilm-G1-Snow-v0"),
                      ("slope_ice",  "Isaac-SlopeFilm-G1-Ice-v0")]:
        print(f"\\n=== {{tag}} ===", flush=True)
        try:
            cfg = parse_env_cfg(task, device="cuda:0", num_envs=1)
            cfg.viewer.origin_type = "asset_root"
            cfg.viewer.asset_name = "robot"
            cfg.viewer.env_index = 0
            cfg.viewer.eye = (4.5, 4.5, 3.0)     # back and well above the relief
            cfg.viewer.lookat = (0.0, 0.0, 0.8)
            cfg.viewer.resolution = (960, 540)
            env = gym.make(task, cfg=cfg, render_mode="rgb_array")
            obs_d, _ = env.reset(); obs = obs_d["policy"]
            frames, falls = [], 0.0
            with torch.inference_mode():
                for i in range(STEPS):
                    obs_d, _, term, trunc, _ = env.step(policy(obs))
                    obs = obs_d["policy"]
                    falls += float(term.float().sum().item())
                    if i %  2 == 0:
                        f = env.unwrapped.render()
                        if f is not None:
                            frames.append(np.asarray(f))
            env.close()
            if frames:
                p = OUT / f"slope_{{tag}}.mp4"
                imageio.mimwrite(p, frames, fps=25, quality=8, macro_block_size=1)
                report[tag] = {{"falls": falls, "steps": STEPS,
                               "steps_between_falls": round(STEPS/(falls+1e-9), 1)
                                                      if falls else STEPS,
                               "file": str(p)}}
                print(f"WROTE {{p}} {{len(frames)}} frames, {{falls:.0f}} falls "
                      f"= 1 per {{STEPS/(falls+1e-9) if falls else STEPS:.0f}} steps",
                      flush=True)
            else:
                report[tag] = {{"error": "no frames"}}
        except Exception as e:
            import traceback; traceback.print_exc(); report[tag] = {{"error": repr(e)}}

    (OUT / "slope_film_report.json").write_text(json.dumps(report, indent=2))
    print("\\n" + json.dumps(report, indent=2), flush=True)
    app.close()
''')
pathlib.Path("sfilm.py").write_text(FILM)
