def sh(cmd, timeout, label, tail=12):
    """Never let one slow step kill the job.

    The first run of this script died with TimeoutExpired propagating out of the
    export stage: rough-terrain generation plus Isaac Sim startup exceeded the cap,
    and because subprocess.run was not wrapped, a slow step became a fatal one.
    Record the timeout and carry on -- the caller decides whether it was fatal.
    """
    print(f"\n$ {cmd}", flush=True)
    try:
        p = subprocess.run(cmd, shell=True, timeout=timeout,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        print("\n".join(p.stdout.splitlines()[-tail:]), flush=True)
        return p.returncode == 0
    except subprocess.TimeoutExpired:
        print(f"[{label}] TIMEOUT after {timeout}s -- continuing", flush=True)
        return False


