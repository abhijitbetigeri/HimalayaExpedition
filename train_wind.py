"""Objective C: wind resistance -- on ice, on slopes.

Wind exists in the MuJoCo track (`wind.py`, drag + centre-of-pressure torque +
AR(1) gusts) but nothing trains there, so the capability has never been
demonstrated. Isaac Lab already has the mechanism: an event term that applies an
external force/torque to a body. Sustained wind is that term in `interval` mode
with a short interval, rather than the usual once-per-reset shove.

Built on the ice+slope config that reached 93.5%, so this is one change from a
known-good recipe -- the discipline that has separated every run that worked here
from every run that did not.

Force scale: the G1 is ~35 kg. 40-90 N lateral against a walking humanoid is a
stiff, shoving wind -- enough to require a postural response, not so much that it
is simply thrown. Applied at the torso, which is where a real gust loads a body.

Wind is NOT in the policy observation, deliberately. A real robot has no
anemometer; it must infer loading from its IMU and joint tracking error. That is
the same argument `CLAUDE.md` makes for the MuJoCo version, and it is what makes
the learned behaviour transferable rather than a cheat.

Run:
  hf jobs uv run --detach --namespace iteratehack --flavor l40sx1 --timeout 3h \
      --env OMNI_KIT_ACCEPT_EULA=YES \
      -v hf://buckets/iteratehack/jobs-artifacts:/mnt \
      --label name=himalaya-traction --label task=train-wind \
      train_wind.py
"""

import os
