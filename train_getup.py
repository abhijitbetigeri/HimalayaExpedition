def sh(cmd, timeout, label, tail=15):
    print(f"\n$ {cmd}", flush=True)
    t0 = time.time()
    # executable=/bin/bash: shell=True defaults to /bin/sh (dash), which does not
    # support `set -o pipefail`, and the training command exited rc=2 before doing
    # anything at all.
    p = subprocess.run(cmd, shell=True, timeout=timeout, executable="/bin/bash",
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    print("\n".join(p.stdout.splitlines()[-tail:]), flush=True)
    print(f"[{label}] rc={p.returncode} in {time.time()-t0:.0f}s", flush=True)
    return p.returncode == 0


