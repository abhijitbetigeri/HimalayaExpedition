    agent_cfg.max_iterations = MAX_ITER

    env = gym.make(TASK, cfg=env_cfg)
    env = RslRlVecEnvWrapper(env)
    runner = OnPolicyRunner(env, agent_cfg.to_dict(), log_dir=LOG_DIR, device="cuda:0")
