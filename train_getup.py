(G1DIR / "getup_env_cfg.py").write_text(textwrap.dedent('''
    """G1 fall recovery on ice. Generated by train_getup.py."""
    import os

    import isaaclab.envs.mdp as mdp
    from isaaclab.managers import RewardTermCfg as RewTerm
    from isaaclab.managers import SceneEntityCfg
    from isaaclab.utils.configclass import configclass

    from .flat_env_cfg import G1FlatEnvCfg

    import torch
    from isaaclab.assets import Articulation
    from isaaclab.envs import ManagerBasedRLEnv

    # G1 pelvis height standing.
    STAND_HEIGHT = 0.74

    # Read straight from the environment: this module is generated as a plain
    # string, so interpolating would mean escaping every dict literal in it.
    Z_MIN = float(os.environ.get("GETUP_Z_MIN", "-0.45"))
    Z_MAX = float(os.environ.get("GETUP_Z_MAX", "-0.05"))
    ROLL = float(os.environ.get("GETUP_ROLL", "1.8"))
    EPISODE_S = float(os.environ.get("GETUP_EPISODE_S", "10.0"))


    def standing_bonus(env: ManagerBasedRLEnv,
                       asset_cfg: SceneEntityCfg = SceneEntityCfg("robot")):
        """Strictly POSITIVE, ~0 when prone, maximal standing upright and tall.

        The whole point is to give recovery something to climb toward. Height and
        uprightness are multiplied, not added, so the robot cannot collect reward
        by rearing up while still face-down, nor by lying flat but level.

        projected_gravity_b[:, 2] is -1 when the torso is upright and ~0 on its
        side, so (-g_z) maps cleanly to [0, 1] as an uprightness score.
        """
        asset: Articulation = env.scene[asset_cfg.name]
        h = asset.data.root_pos_w[:, 2]
        height_score = torch.exp(-torch.abs(h - STAND_HEIGHT) / 0.25)
        upright = torch.clamp(-asset.data.projected_gravity_b[:, 2], 0.0, 1.0)
        return height_score * upright


    @configclass
    class G1GetupIceEnvCfg(G1FlatEnvCfg):
        def __post_init__(self):
            super().__post_init__()

            # ---- start on the ground -----------------------------------------
            # z is an OFFSET from the default root height, so -0.45 puts the pelvis
            # near the floor. Full yaw, and roll/pitch wide enough to produce
            # face-down, back-down and side-down starts rather than one pose.
            # v1 started FULLY sprawled -- z -0.50..-0.40 with roll across the
            # whole circle -- and after 3000 iterations success_rate was 0.000 with
            # base_height -1.83, i.e. it never got off the ground. Prone-to-standing
            # is long-horizon and that start gives almost no gradient toward
            # standing.
            #
            # v2 spans the range instead: some episodes start nearly upright (a
            # stumble), some half-down, some fully prone. The easy ones bootstrap a
            # recovery behaviour that the hard ones can then extend -- a curriculum
            # by sampling rather than by scheduling, which needs no extra machinery.
            self.events.reset_base.params["pose_range"] = {
                "x": (-0.3, 0.3), "y": (-0.3, 0.3), "z": (Z_MIN, Z_MAX),
                "roll": (-ROLL, ROLL), "pitch": (-1.0, 1.0), "yaw": (-3.14, 3.14),
            }
            self.events.reset_base.params["velocity_range"] = {
                "x": (0.0, 0.0), "y": (0.0, 0.0), "z": (0.0, 0.0),
                "roll": (0.0, 0.0), "pitch": (0.0, 0.0), "yaw": (0.0, 0.0),
            }
            # Sprawled limbs, not a tidy default pose.
            self.events.reset_robot_joints.params["position_range"] = (0.6, 1.4)

            # ---- being on the ground is the PREMISE, not a failure -----------
            # base_contact is left EXACTLY as shipped. Both ways of disabling it
            # break Isaac: setting it to None segfaults at a fixed 312 s (identical
            # at 64/30 and 4096/3000, so not a scale problem), and raising its
            # threshold aborts at 22 s. The env is only viable if the torso never
            # touches the ground -- which a CROUCH start guarantees while still
            # being the second half of a real get-up.

            # Long enough to actually complete a recovery.
            self.episode_length_s = EPISODE_S

            # ---- nothing to track while lying down ---------------------------
            self.commands.base_velocity.ranges.lin_vel_x = (0.0, 0.0)
            self.commands.base_velocity.ranges.lin_vel_y = (0.0, 0.0)
            self.commands.base_velocity.ranges.ang_vel_z = (0.0, 0.0)
            self.rewards.track_lin_vel_xy_exp.weight = 0.0
            self.rewards.track_ang_vel_z_exp.weight = 0.0
            self.rewards.feet_air_time.weight = 0.0
            self.rewards.feet_slide.weight = 0.0
            self.rewards.termination_penalty.weight = 0.0

            # ---- stand up and stay level -------------------------------------
            # THE BUG IN v1 AND v2: every remaining reward was NEGATIVE. The
            # positive terms (velocity tracking, feet air time) were zeroed because
            # they are meaningless lying down, which left only penalties -- so with
            # no termination the optimal policy was TO NOT MOVE. Lying still
            # minimises torque and action-rate cost. Both runs converged to exactly
            # that: base_height -1.81 and -1.83, success 0.000, twice.
            #
            # Recovery needs something to CLIMB TOWARD. `standing_bonus` is
            # strictly positive, near zero when prone and maximal when upright and
            # tall, so the gradient points off the ground from the first frame.
            self.rewards.standing = RewTerm(func=standing_bonus, weight=8.0)

            self.rewards.flat_orientation_l2.weight = -2.0
            self.rewards.base_height = RewTerm(
                func=mdp.base_height_l2,
                weight=-2.0,
                params={"target_height": STAND_HEIGHT,
                        "asset_cfg": SceneEntityCfg("robot")},
            )
            # Standing up is a large, fast, high-torque motion. The locomotion
            # defaults penalise exactly that because they are tuned for efficient
            # walking, so they were fighting the task. Relaxed by ~10x.
            self.rewards.action_rate_l2.weight = -0.001
            self.rewards.dof_torques_l2.weight = -1.0e-6
            self.rewards.dof_acc_l2.weight = -1.0e-8
            # Deviation penalties assume a nominal standing pose; getting up
            # requires leaving it entirely.
            self.rewards.joint_deviation_hip.weight = 0.0
            self.rewards.joint_deviation_arms.weight = 0.0
            self.rewards.joint_deviation_torso.weight = 0.0

            # ---- contact budget ----------------------------------------------
            # Removing base_contact termination means robots lie in deep
            # penetrating contact for the WHOLE episode instead of resetting on
            # touchdown -- unique to this task -- and at 4096 envs that overflowed
            # PhysX's rigid-patch buffer, SEGFAULTING (rc=139) rather than raising.
            #
            # Replacing self.sim to raise the buffer made it worse (SIGABRT in 22 s):
            # G1FlatEnvCfg builds sim from a PresetCfg carrying BOTH a PhysX and a
            # Newton MJWarp preset, and substituting a plain SimulationCfg discards
            # that structure. Fewer environments achieves the same thing without
            # touching a config shape I do not fully control.

            # ---- on ice ------------------------------------------------------
            # Hands and feet need purchase to push against; 0.06 is what a limb
            # slides on. Spanning up to rock keeps it usable on mixed ground.
            self.events.physics_material.params["static_friction_range"] = (0.05, 1.0)
            self.events.physics_material.params["dynamic_friction_range"] = (0.04, 0.9)


    @configclass
    class G1GetupIceEnvCfg_PLAY(G1GetupIceEnvCfg):
        def __post_init__(self):
            super().__post_init__()
            self.scene.num_envs = 16
            self.observations.policy.enable_corruption = False
            self.events.push_robot = None
            self.events.base_external_force_torque = None
'''))

