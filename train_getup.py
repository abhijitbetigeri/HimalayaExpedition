"""Fall recovery: the G1 starts on the ground and has to stand back up -- on ice.

Track 1's second bullet, and a genuinely different problem from locomotion rather
than a variation on it:

  * Falling is the START state, not the failure. `terminations.base_contact` must
    be removed or every episode ends on the first frame.
  * There is nothing to track. Velocity-tracking rewards are meaningless lying on
    your back, so they go to zero and are replaced by "get the torso up and level".
  * Ice makes it harder in a specific way: pushing up needs the hands and feet to
    PURCHASE against the ground, and mu=0.06 is what a stuck limb slides on.

Reward shape, deliberately small: height and uprightness carry the task, the stock
regularisers (torque, action rate, joint limits) keep the motion physical. A
hand-tuned recovery reward would be a second research project; this is the smallest
thing that expresses "end up standing".

Starting poses are randomised across roll and pitch, so the policy has to recover
from face-down, back-down and side-down rather than memorising one scripted
get-up.

Run:
  hf jobs uv run --detach --namespace iteratehack --flavor a100-large --timeout 3h \
      --env OMNI_KIT_ACCEPT_EULA=YES \
      -v hf://buckets/iteratehack/jobs-artifacts:/mnt \
      --label name=himalaya-traction --label task=train-getup \
      train_getup.py
"""

